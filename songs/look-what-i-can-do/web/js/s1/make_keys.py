# Writes keys.js: every footage sequence in web/media/hd (frame count, mean brightness, share of near-white pixels),
# so the page knows what exists without a directory listing. Re-run whenever new clips land:
#   python3 web/js/s1/make_keys.py
import json, os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
HD = os.path.normpath(os.path.join(HERE, '..', '..', 'media', 'hd'))
out = {}
for k in sorted(os.listdir(HD)):
    d = os.path.join(HD, k)
    if not os.path.isdir(d):
        continue
    fs = sorted(f for f in os.listdir(d) if f.endswith('.jpg'))
    if not fs:
        continue
    lum, white = [], []
    for f in fs[:: max(1, len(fs) // 8)]:
        im = Image.open(os.path.join(d, f)).convert('L').resize((96, 54))
        px = list(im.getdata())
        lum.append(sum(px) / len(px) / 255)
        white.append(sum(1 for p in px if p > 235) / len(px))
    out[k] = {'n': len(fs), 'lum': round(sum(lum) / len(lum), 3), 'lumMax': round(max(lum), 3), 'white': round(max(white), 3)}
with open(os.path.join(HERE, 'keys.js'), 'w') as fh:
    fh.write('// generated by make_keys.py: footage sequences in web/media/hd (n frames at 30 fps, brightness stats)\n')
    fh.write('export const KEYS = ' + json.dumps(out, indent=0).replace('\n', '') + ';\n')
print(len(out), 'keys')
for k, v in out.items():
    print(k, v)
