"""Living Earth film: timing/timing_v0.yaml (+ build/timed.json word times) -> remotion/src/le/film/timing.gen.ts.
    .venv/bin/python living_earth/le_timing_gen.py
Re-run whenever the timing file changes; beats.ts uses anchors ('chorus1/L2+0.3'), never raw seconds, so nothing else moves.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); SONG = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(SONG, "timing"))
from timing import load
T = load(); R = T.resolved()
timed = json.load(open(os.path.join(SONG, "build", "timed.json")))
bysec = {}
for e in timed:
    bysec.setdefault(e["sec"], []).append(e)
lines = {}
for sid in R["order"]:
    out = []
    for i, (t, txt) in enumerate(zip(R["lines"][sid], R["lyric"][sid] or [])):
        words = []
        cand = bysec.get(sid, [])
        if i < len(cand) and cand[i]["text"].strip().lower()[:12] == str(txt).strip().lower()[:12]:
            sh = t - cand[i]["s"]
            words = [[round(w + sh, 3), s] for w, s in zip(cand[i]["wt"], cand[i]["words"])]
        out.append({"t": round(t, 3), "text": txt, "words": words})
    lines[sid] = out
data = {"fps": 30, "duration": round(R["duration"], 3), "bpm": R["bpm"], "bar": R["bar_s"], "order": R["order"],
        "sections": {k: [round(a, 3), round(b, 3)] for k, (a, b) in R["sections"].items()}, "lines": lines}
dst = os.path.join(SONG, "remotion", "src", "le", "film", "timing.gen.ts")
open(dst, "w").write("// GENERATED by living_earth/le_timing_gen.py from timing/timing_v0.yaml + build/timed.json. Do not edit; re-run the script.\n"
                     "export type Line = { t: number; text: string; words: [number, string][] };\nexport const TIMING: { fps: number; duration: number; bpm: number; bar: number; order: string[]; sections: Record<string, [number, number]>; lines: Record<string, Line[]> } = " + json.dumps(data, indent=0) + ";\n")
print("wrote", dst, f"duration {data['duration']} s,", sum(len(v) for v in lines.values()), "lines,",
      sum(1 for v in lines.values() for l in v if l["words"]), "with words")
